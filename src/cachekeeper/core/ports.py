from typing import Protocol

from .report import RequestRecord
from .stats import CacheStats


class Clock(Protocol):
    def now(self) -> float: ...

    def monotonic(self) -> float: ...


class StatsTap(Protocol):
    def feed(self, chunk: bytes) -> None: ...

    def finish(self, ttft_ms: float | None, prompt_chars: int) -> CacheStats: ...


class Backend(Protocol):
    name: str
    version_path: str
    probe_path: str

    def version(self, payload: object) -> str | None: ...

    def tap(self, model: str) -> StatsTap: ...

    def probe_body(self, model: str, messages: list[dict[str, str]]) -> dict[str, object]: ...


class Storage(Protocol):
    def start(self) -> None: ...

    async def stop(self) -> None: ...

    def save(self, record: RequestRecord, body: bytes | None) -> None: ...

    def records(self, since: float, model: str | None) -> list[RequestRecord]: ...

    def record(self, request_id: str) -> RequestRecord | None: ...

    def body(self, request_id: str) -> bytes | None: ...
